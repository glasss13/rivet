use crate::elf::Function;
use anyhow::{Context, Result, bail, ensure};
use iced_x86::{
    Code, ConditionCode, Decoder, DecoderOptions, EncodingKind, Instruction, Mnemonic, OpKind,
    Register,
};
use std::fmt::Write;

pub fn module(function: &Function<'_>, namespace: &str) -> Result<String> {
    ensure!(
        !namespace.is_empty()
            && namespace.split('.').all(|part| !part.is_empty()
                && !part.chars().any(|c| c == '«' || c == '»' || c.is_control())),
        "invalid Lean namespace"
    );
    let namespace = namespace
        .split('.')
        .map(|part| format!("«{part}»"))
        .collect::<Vec<_>>()
        .join(".");
    let instructions: Vec<_> =
        Decoder::with_ip(64, function.bytes, function.address, DecoderOptions::NONE)
            .into_iter()
            .collect();
    let mut source = format!(
        "-- Generated by rivet-import. Function code only; memory is supplied by the caller.\nmodule\npublic import Rivet\n@[expose] public section\nnamespace {namespace}\n\ndef entry : Nat := {:#x}\ndef program : Rivet.Program := [\n",
        function.address
    );
    for (index, instruction) in instructions.iter().enumerate() {
        let offset = (instruction.ip() - function.address) as usize;
        let bytes = &function.bytes[offset..offset + instruction.len()];
        let translated =
            operation(instruction, bytes).with_context(|| format!("at {:#x}", instruction.ip()))?;
        if instruction.op0_kind() == OpKind::NearBranch64 {
            ensure!(
                instructions
                    .binary_search_by_key(&instruction.near_branch64(), Instruction::ip)
                    .is_ok(),
                "at {:#x}: branch target is not an instruction boundary inside the function",
                instruction.ip()
            );
        }
        writeln!(
            source,
            "  {{ address := {:#x}, length := {}, op := {} }}{}",
            instruction.ip(),
            instruction.len(),
            translated,
            if index + 1 == instructions.len() {
                ""
            } else {
                ","
            }
        )?;
    }
    writeln!(source, "]\n\nend {namespace}")?;
    Ok(source)
}

fn register(register: Register) -> Result<String> {
    ensure!(
        (register.is_gpr()
            && !matches!(
                register,
                Register::AH | Register::BH | Register::CH | Register::DH
            ))
            || (Register::XMM0..=Register::XMM15).contains(&register),
        "unsupported register {register:?}"
    );
    Ok(format!(".{register:?}").to_ascii_lowercase())
}

fn condition(instruction: &Instruction) -> Result<&'static str> {
    Ok(match instruction.condition_code() {
        ConditionCode::e => "equal",
        ConditionCode::ne => "notEqual",
        ConditionCode::b => "below",
        ConditionCode::ae => "aboveOrEqual",
        ConditionCode::be => "belowOrEqual",
        ConditionCode::a => "above",
        ConditionCode::s => "sign",
        other => bail!("unsupported condition {other:?}"),
    })
}

fn address(instruction: &Instruction) -> Result<String> {
    ensure!(
        !instruction.is_ip_rel_memory_operand(),
        "RIP-relative operands are not supported yet"
    );
    let base = instruction.memory_base();
    let index = instruction.memory_index();
    let optional = |value: Register| -> Result<String> {
        if value == Register::None {
            return Ok("none".into());
        }
        ensure!(
            value.is_gpr64(),
            "only 64-bit memory addressing is supported"
        );
        Ok(format!("some {}", register(value)?))
    };
    let scale = match instruction.memory_index_scale() {
        1 => "one",
        2 => "two",
        4 => "four",
        8 => "eight",
        _ => unreachable!(),
    };
    Ok(format!(
        "{{ base := {}, index := {}, scale := .{scale}, displacement := ({}) }}",
        optional(base)?,
        optional(index)?,
        instruction.memory_displacement64() as i64
    ))
}

fn operand(instruction: &Instruction, index: u32) -> Result<String> {
    Ok(match instruction.op_kind(index) {
        OpKind::Register => {
            let value = instruction.op_register(index);
            format!("(.reg{} {})", value.size() * 8, register(value)?)
        }
        OpKind::Memory => {
            let width = match instruction.memory_size().size() {
                1 => "byte",
                2 => "word",
                4 => "dword",
                8 => "qword",
                _ => bail!("unsupported memory width"),
            };
            format!("(.memory .{width} {})", address(instruction)?)
        }
        OpKind::Immediate8 | OpKind::Immediate16 | OpKind::Immediate32 | OpKind::Immediate64 => {
            format!("(.immediate {})", instruction.immediate(index))
        }
        OpKind::Immediate8to16
        | OpKind::Immediate8to32
        | OpKind::Immediate8to64
        | OpKind::Immediate32to64 => {
            format!("(.immediate ({}))", instruction.immediate(index) as i64)
        }
        kind => bail!("unsupported operand {kind:?}"),
    })
}

fn operation(instruction: &Instruction, bytes: &[u8]) -> Result<String> {
    use Mnemonic::*;
    ensure!(!instruction.is_invalid(), "invalid or truncated encoding");
    ensure!(
        instruction.encoding() == EncodingKind::Legacy
            && !instruction.has_lock_prefix()
            && !instruction.has_rep_prefix()
            && !instruction.has_repne_prefix()
            && !instruction.has_segment_prefix(),
        "unsupported encoding or prefix"
    );
    // Address-size overrides are deliberately outside this initial importer.
    // TODO: just support this
    ensure!(
        !bytes
            .iter()
            .take_while(|&&b| matches!(
                b,
                0x40..=0x4f
                    | 0x66
                    | 0x67
                    | 0xf0
                    | 0xf2
                    | 0xf3
                    | 0x26
                    | 0x2e
                    | 0x36
                    | 0x3e
                    | 0x64
                    | 0x65
            ))
            .any(|&b| b == 0x67),
        "address-size overrides are not supported"
    );

    let first = || operand(instruction, 0);
    let second = || operand(instruction, 1);
    let register64 = || -> Result<String> {
        ensure!(
            instruction.op0_kind() == OpKind::Register && instruction.op0_register().is_gpr64(),
            "this instruction requires a 64-bit register"
        );
        register(instruction.op0_register())
    };
    Ok(match instruction.mnemonic() {
        Add | Sub | Sbb | Cmp | Test | And | Or | Xor => format!(
            ".binary .{} {} {}",
            format!("{:?}", instruction.mnemonic()).to_ascii_lowercase(),
            first()?,
            second()?
        ),
        Not => format!(".not {}", first()?),
        Shl | Shr => {
            ensure!(
                instruction.op0_kind() == OpKind::Register
                    && (instruction.op0_register().is_gpr32()
                        || instruction.op0_register().is_gpr64())
                    && instruction.op1_kind() == OpKind::Immediate8,
                "shifts require a 32/64-bit register and an immediate count"
            );
            format!(
                ".shift .{} {} {}",
                format!("{:?}", instruction.mnemonic()).to_ascii_lowercase(),
                first()?,
                instruction.immediate8()
            )
        }
        Imul => {
            ensure!(
                instruction.op_count() >= 2,
                "one-operand IMUL is not supported"
            );
            let immediate = if instruction.op_count() == 3 {
                format!("(some ({}))", instruction.immediate(2) as i64)
            } else {
                "none".into()
            };
            format!(".imul {} {} {immediate}", first()?, second()?)
        }
        Sete | Setne | Setb | Setae | Setbe | Seta | Sets => {
            format!(".setcc .{} {}", condition(instruction)?, first()?)
        }
        Cmove | Cmovne | Cmovb | Cmovae | Cmovbe | Cmova | Cmovs => {
            format!(
                ".cmovcc .{} {} {}",
                condition(instruction)?,
                first()?,
                second()?
            )
        }
        Movd => {
            ensure!(
                instruction.code() == Code::Movd_xmm_rm32
                    && instruction.op1_kind() == OpKind::Register,
                "MOVD requires an XMM destination and a 32-bit register source"
            );
            format!(
                ".movd {} {}",
                register(instruction.op0_register())?,
                register(instruction.op1_register())?
            )
        }
        Pshufd => {
            ensure!(
                instruction.code() == Code::Pshufd_xmm_xmmm128_imm8
                    && instruction.op1_kind() == OpKind::Register,
                "PSHUFD requires register operands"
            );
            format!(
                ".pshufd {} {} {}",
                register(instruction.op0_register())?,
                register(instruction.op1_register())?,
                instruction.immediate8()
            )
        }
        Movups | Movdqu => {
            let name = format!("{:?}", instruction.mnemonic()).to_ascii_lowercase();
            match (instruction.op0_kind(), instruction.op1_kind()) {
                (OpKind::Register, OpKind::Memory) => format!(
                    ".loadXmm .{name} {} {}",
                    register(instruction.op0_register())?,
                    address(instruction)?
                ),
                (OpKind::Memory, OpKind::Register) => format!(
                    ".storeXmm .{name} {} {}",
                    address(instruction)?,
                    register(instruction.op1_register())?
                ),
                _ => bail!("{name} requires a memory operand"),
            }
        }
        Mov => format!(".mov {} {}", first()?, second()?),
        Lea => format!(".lea {} {}", register64()?, address(instruction)?),
        Movzx => {
            ensure!(
                instruction.op0_register().is_gpr32(),
                "MOVZX requires a 32-bit destination"
            );
            format!(
                ".movzx {} {}",
                register(instruction.op0_register())?,
                second()?
            )
        }
        Movsxd => format!(".movsxd {} {}", register64()?, second()?),
        Inc | Dec | Push | Pop => format!(
            ".{} {}",
            format!("{:?}", instruction.mnemonic()).to_ascii_lowercase(),
            register64()?
        ),
        Jmp => {
            ensure!(
                instruction.op0_kind() == OpKind::NearBranch64,
                "only direct 64-bit-mode jumps are supported"
            );
            format!(".jmp {:#x}", instruction.near_branch64())
        }
        Je | Jne | Jb | Jae | Jbe | Ja | Js => {
            ensure!(
                instruction.op0_kind() == OpKind::NearBranch64,
                "unsupported branch form"
            );
            format!(
                ".jcc .{} {:#x}",
                condition(instruction)?,
                instruction.near_branch64()
            )
        }
        Ret if instruction.code() == Code::Retnq => ".ret".into(),
        _ => bail!("unsupported instruction {:?}", instruction.code()),
    })
}
