//! Untrusted convenience importer. Lean's reference parser certifies the output.
mod sha256;
use std::{collections::BTreeMap, env, fs, process::ExitCode};

fn identifier(s: &str) -> bool {
    !s.is_empty()
        && !s.as_bytes()[0].is_ascii_digit()
        && s.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'_')
}
fn tokens(s: &str) -> Vec<String> {
    s.replace(',', " , ")
        .replace('\t', " ")
        .split(' ')
        .filter(|s| !s.is_empty())
        .map(str::to_owned)
        .collect()
}
fn parse(source: &str) -> Result<String, String> {
    let mut labels = BTreeMap::new();
    let mut lines = Vec::new();
    let mut function = None;
    for (index, raw) in source.split('\n').enumerate() {
        let line = index + 1;
        let s = raw
            .split('#')
            .next()
            .unwrap()
            .trim_matches([' ', '\t', '\r']);
        if s.is_empty() {
            continue;
        }
        let fail = |message: &str| format!("line {line}: {message}");
        if s.contains(';') {
            return Err(fail("semicolon is forbidden"));
        }
        let ts = tokens(s);
        let t: Vec<_> = ts.iter().map(String::as_str).collect();
        if s.starts_with('.') {
            match t.as_slice() {
                [".globl", name]
                    if function.is_none()
                        && labels.is_empty()
                        && lines.is_empty()
                        && identifier(name) =>
                {
                    function = Some(name.to_string())
                }
                _ => return Err(fail("unsupported declaration")),
            }
            continue;
        }
        if let Some(name) = s.strip_suffix(':') {
            if !identifier(name) || labels.contains_key(name) {
                return Err(fail("invalid or duplicate label"));
            }
            if labels.is_empty() && function.as_deref() != Some(name) {
                return Err(fail("first label must name the function"));
            }
            labels.insert(name.to_owned(), lines.len());
            continue;
        }
        if labels.is_empty() {
            return Err(fail("instruction before function entry"));
        }
        lines.push((line, ts));
    }
    if lines.is_empty() {
        return Err("empty function".into());
    }
    let mut result = Vec::new();
    for (line, ts) in &lines {
        let t: Vec<_> = ts.iter().map(String::as_str).collect();
        let op = match t.as_slice() {
            ["xor", "eax", ",", "eax"] => ".xor .eax .eax".into(),
            ["test", "rsi", ",", "rsi"] => ".test .rsi .rsi".into(),
            ["movzx", "edx", ",", "BYTE", "PTR", "[rdi]"] => ".movzx .edx (.bytePtr .rdi)".into(),
            ["add", "rax", ",", "rdx"] => ".add .rax .rdx".into(),
            ["inc", "rdi"] => ".inc .rdi".into(),
            ["dec", "rsi"] => ".dec .rsi".into(),
            ["ret"] => ".ret".into(),
            [op @ ("jz" | "jnz"), label] => {
                let target = labels
                    .get(*label)
                    .filter(|&&i| i < lines.len())
                    .ok_or_else(|| format!("line {line}: unresolved/outside target: {label}"))?;
                format!(".{op} {target}")
            }
            _ => return Err(format!("line {line}: unsupported instruction")),
        };
        result.push(format!("  ⟨{op}, {line}⟩"));
    }
    Ok(result.join(",\n"))
}

// Lean string syntax, not Rust's Debug syntax. Preserve original UTF-8 and line endings.
fn lean_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() && (c as u32) < 128 => {
                out.push_str(&format!("\\x{:02x}", c as u32))
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
fn generate(data: &[u8], namespace: &str) -> Result<String, String> {
    if !identifier(namespace) {
        return Err("namespace must be an ASCII identifier".into());
    }
    let source = std::str::from_utf8(data).map_err(|e| format!("invalid UTF-8: {e}"))?;
    let program = parse(source)?;
    let literal = lean_string(source);
    let hash = sha256::hex(data);
    Ok(format!(
        "-- Generated by asm-to-lean (Rust); do not edit.\n\
import Verification.Parser\n\
set_option maxRecDepth 10000\n\
set_option maxHeartbeats 4000000\n\
namespace Verification.{namespace}\n\
def source : String := {literal}\n\
def sha256 : String := \"{hash}\"\n\
def program : Program := [\n{program}]\n\
theorem certificate : parse source = .ok program := by decide +kernel\n\
end Verification.{namespace}\n"
    ))
}
fn execute() -> Result<(), String> {
    let args: Vec<_> = env::args().collect();
    if !(3..=4).contains(&args.len()) {
        return Err("usage: asm-to-lean INPUT.s OUTPUT.lean [NAMESPACE]".into());
    }
    let data = fs::read(&args[1]).map_err(|e| format!("{}: {e}", args[1]))?;
    let output = generate(&data, args.get(3).map_or("Imported", String::as_str))?;
    fs::write(&args[2], output).map_err(|e| format!("{}: {e}", args[2]))
}
fn main() -> ExitCode {
    match execute() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("{e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn preserves_mnemonics_operands_and_targets() {
        let output = generate(include_bytes!("../../fixtures/sum_bytes.s"), "Imported").unwrap();
        for text in [
            ".xor .eax .eax",
            ".test .rsi .rsi",
            ".movzx .edx (.bytePtr .rdi)",
            ".jz 8",
            ".jnz 3",
        ] {
            assert!(output.contains(text));
        }
    }
    #[test]
    fn rejects_invalid_utf8_and_namespace() {
        assert!(generate(&[0xff], "Imported").is_err());
        assert!(generate(b"", "X\nend Verification").is_err());
    }
    #[test]
    fn escapes_lean_literals() {
        assert_eq!(lean_string("\"\\\n\r\t\0é"), "\"\\\"\\\\\\n\\r\\t\\x00é\"");
    }
}
