use crate::elf::MemoryRegion;
use anyhow::{Result, ensure};
use rivet_import::{
    Instruction,
    operand::{Address, Operand},
    program::Operation,
};
use std::fmt::Write;

pub fn module(
    instructions: &[Instruction],
    entry: u64,
    regions: &[MemoryRegion<'_>],
    namespace: &str,
) -> Result<String> {
    ensure!(
        !namespace.is_empty()
            && namespace.split('.').all(|part| !part.is_empty()
                && !part.chars().any(|c| c == '«' || c == '»' || c.is_control())),
        "invalid Lean namespace"
    );
    let namespace = namespace
        .split('.')
        .map(|part| format!("«{part}»"))
        .collect::<Vec<_>>()
        .join(".");
    let mut source = format!(
        "-- Generated by rivet-import. Instructions and ELF-declared initial memory.\nmodule\npublic import Rivet\n@[expose] public section\nnamespace {namespace}\n\ndef entry : Nat := {:#x}\ndef program : Rivet.Program := [\n",
        entry
    );
    for (index, instruction) in instructions.iter().enumerate() {
        let translated = operation(&instruction.op);
        writeln!(
            source,
            "  {{ address := {:#x}, length := {}, op := {} }}{}",
            instruction.address,
            instruction.length,
            translated,
            if index + 1 == instructions.len() {
                ""
            } else {
                ","
            }
        )?;
    }
    writeln!(source, "]\n\ndef regions : List Rivet.MemoryRegion := [")?;
    for (index, region) in regions.iter().enumerate() {
        writeln!(
            source,
            "  {{ address := {:#x}, size := {:#x}, readable := {}, writable := {}, contents := let bytes : ByteArray := ⟨#[",
            region.address, region.size, region.readable, region.writable
        )?;
        for chunk in region.bytes.chunks(16) {
            let bytes = chunk
                .iter()
                .map(|byte| format!("{byte:#04x}"))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(source, "    {bytes},")?;
        }
        writeln!(
            source,
            "  ]⟩; fun offset => (bytes[offset]?.getD 0).toFin }}{}",
            if index + 1 < regions.len() { "," } else { "" }
        )?;
    }
    // An address index lets proofs look up instructions in logarithmic time.
    writeln!(source, "]\n\nrivet_index program\n\nend {namespace}")?;
    Ok(source)
}

fn name(value: impl std::fmt::Debug) -> String {
    format!(".{value:?}").to_ascii_lowercase()
}

fn address(value: &Address) -> String {
    let optional = |register| match register {
        Some(register) => format!("some {}", name(register)),
        None => "none".into(),
    };
    format!(
        "{{ base := {}, index := {}, scale := {}, displacement := ({}) }}",
        optional(value.base),
        optional(value.index),
        name(value.scale),
        value.displacement
    )
}

fn operand(value: &Operand) -> String {
    match value {
        Operand::Reg8 { register } => format!("(.reg8 {})", name(register)),
        Operand::Reg16 { register } => format!("(.reg16 {})", name(register)),
        Operand::Reg32 { register } => format!("(.reg32 {})", name(register)),
        Operand::Reg64 { register } => format!("(.reg64 {})", name(register)),
        Operand::Memory {
            width,
            address: value,
        } => format!("(.memory {} {})", name(width), address(value)),
        Operand::Immediate { value } => format!("(.immediate ({value}))"),
    }
}

fn condition(value: rivet_import::program::Condition) -> &'static str {
    use rivet_import::program::Condition::*;
    match value {
        Equal => ".equal",
        NotEqual => ".notEqual",
        Below => ".below",
        AboveOrEqual => ".aboveOrEqual",
        BelowOrEqual => ".belowOrEqual",
        Above => ".above",
        Sign => ".sign",
    }
}

fn operation(value: &Operation) -> String {
    use Operation::*;
    match value {
        Nop => ".nop".into(),
        Binary {
            operation,
            destination,
            source,
        } => format!(
            ".binary {} {} {}",
            name(operation),
            operand(destination),
            operand(source)
        ),
        Mov {
            destination,
            source,
        } => format!(".mov {} {}", operand(destination), operand(source)),
        Lea {
            destination,
            source,
        } => format!(".lea {} {}", name(destination), address(source)),
        Movzx {
            destination,
            source,
        } => format!(".movzx {} {}", name(destination), operand(source)),
        Movsxd {
            destination,
            source,
        } => format!(".movsxd {} {}", name(destination), operand(source)),
        Jmp { target } => format!(".jmp {target:#x}"),
        Jcc {
            condition: value,
            target,
        } => format!(".jcc {} {target:#x}", condition(*value)),
        Setcc {
            condition: value,
            destination,
        } => format!(".setcc {} {}", condition(*value), operand(destination)),
        Cmovcc {
            condition: value,
            destination,
            source,
        } => format!(
            ".cmovcc {} {} {}",
            condition(*value),
            operand(destination),
            operand(source)
        ),
        Inc { destination } => format!(".inc {}", name(destination)),
        Dec { destination } => format!(".dec {}", name(destination)),
        Ret => ".ret".into(),
        Call { target } => format!(".call {target:#x}"),
        Not { destination } => format!(".not {}", operand(destination)),
        Imul {
            destination,
            source,
            immediate,
        } => format!(
            ".imul {} {} {}",
            operand(destination),
            operand(source),
            immediate.map_or("none".into(), |value| format!("(some ({value}))"))
        ),
        Shift {
            operation,
            destination,
            count,
        } => format!(
            ".shift {} {} {count}",
            name(operation),
            operand(destination)
        ),
        LoadXmm {
            operation,
            destination,
            source,
        } => format!(
            ".loadXmm {} {} {}",
            name(operation),
            name(destination),
            address(source)
        ),
        StoreXmm {
            operation,
            destination,
            source,
        } => format!(
            ".storeXmm {} {} {}",
            name(operation),
            address(destination),
            name(source)
        ),
        Movd {
            destination,
            source,
        } => format!(".movd {} {}", name(destination), name(source)),
        Pshufd {
            destination,
            source,
            order,
        } => format!(".pshufd {} {} {order}", name(destination), name(source)),
        Push { source } => format!(".push {}", name(source)),
        Pop { destination } => format!(".pop {}", name(destination)),
    }
}
