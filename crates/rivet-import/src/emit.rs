use crate::elf::Segment;
use anyhow::{Result, ensure};
use rivet_import::{
    Instruction,
    operand::{Address, Operand},
    program::Operation,
};
use std::fmt::Write;

pub fn module(
    instructions: &[Instruction],
    entry: u64,
    segments: &[Segment<'_>],
    namespace: &str,
) -> Result<String> {
    ensure!(
        !namespace.is_empty()
            && namespace.split('.').all(|part| !part.is_empty()
                && !part.chars().any(|c| c == '«' || c == '»' || c.is_control())),
        "invalid Lean namespace"
    );
    let namespace = namespace
        .split('.')
        .map(|part| format!("«{part}»"))
        .collect::<Vec<_>>()
        .join(".");
    let mut source = format!(
        "-- Generated by rivet-import. Instructions, and the ELF's loadable segments.\nmodule\npublic import Rivet\n@[expose] public section\nnamespace {namespace}\n\ndef entry : BitVec 64 := {:#x}#64\n",
        entry
    );
    program(&mut source, instructions)?;
    loadable_segments(&mut source, segments)?;
    writeln!(source, "\nend {namespace}")?;
    Ok(source)
}

/// Emits the loadable segments: `region_<a>`, the segment at `a` as a region of the
/// image, and `regions`, all of them; `segment_<a>`, its bytes (zero past the file's
/// data); and `Loaded memory`, that memory is the same as those bytes on every
/// segment, as the loader leaves it, with a field `segment_<a>` per segment.
fn loadable_segments(source: &mut String, segments: &[Segment<'_>]) -> std::fmt::Result {
    writeln!(source, "\n-- Loadable segments: addresses and permissions.")?;
    for segment in segments {
        writeln!(
            source,
            "abbrev region_{:x} : Rivet.Region :=\n  {{ base := {:#x}, length := {:#x}, readable := {}, writable := {} }}",
            segment.address, segment.address, segment.size, segment.readable, segment.writable,
        )?;
    }
    let names: Vec<String> = segments.iter().map(|segment| format!("region_{:x}", segment.address)).collect();
    writeln!(source, "def regions : List Rivet.Region := [{}]", names.join(", "))?;
    // One number per segment, read by shifting: Lean computes on number literals in one step, where a
    // literal list of thousands of bytes overflows its recursion limit to compile or to index.
    for segment in segments {
        let digits: String = segment.bytes.iter().rev().map(|byte| format!("{byte:02x}")).collect();
        writeln!(
            source,
            "\n-- The bytes of the segment at {:#x}: byte `i` is digit `i`, base 256, of `bytes`; zero past the\n-- file's data.\ndef segment_{:x} : Rivet.Memory := fun address =>\n  let offset := (address - {:#x}#64).toNat\n  if offset < {} then Fin.ofNat 256 (bytes >>> (8 * offset)) else 0\nwhere bytes : Nat := 0x{}",
            segment.address,
            segment.address,
            segment.address,
            segment.bytes.len(),
            if digits.is_empty() { "0" } else { &digits }
        )?;
    }
    // One field per segment, named after the segment's bytes, so a proof reads
    // `loaded.segment_<a>` whatever the number or order of segments.
    writeln!(
        source,
        "\n-- What the loader guarantees: on each segment, memory is the segment's bytes.\nstructure Loaded (memory : Rivet.Memory) : Prop{}",
        if segments.is_empty() { "" } else { " where" }
    )?;
    for segment in segments {
        writeln!(
            source,
            "  segment_{:x} : region_{:x}.Same segment_{:x} memory",
            segment.address, segment.address, segment.address
        )?;
    }
    Ok(())
}

/// Emits `program` as a chain of suffixes, so that a proof can fetch any
/// instruction in time independent of the program size.
///
/// `program.suffix_<a>` is the program from the instruction at address `a` on;
/// suffixes are listed last to first because each one refers to the next.
/// `program.from_<a> : FetchesFrom program program.suffix_<a> a` follows from
/// the previous instruction's fact by `FetchesFrom.skip`, and Lean checks it.
/// Instructions must have strictly increasing addresses.
fn program(source: &mut String, instructions: &[Instruction]) -> std::fmt::Result {
    let Some(first) = instructions.first() else {
        return writeln!(source, "def program : Rivet.Program := []");
    };
    writeln!(
        source,
        "\n-- The program from each instruction on, last to first."
    )?;
    for (index, instruction) in instructions.iter().enumerate().rev() {
        let rest = match instructions.get(index + 1) {
            Some(next) => format!("program.suffix_{:x}", next.address),
            None => "[]".to_string(),
        };
        writeln!(
            source,
            "def program.suffix_{:x} : Rivet.Program := {{ address := {:#x}#64, length := {}, op := {} }} :: {rest}",
            instruction.address,
            instruction.address,
            instruction.length,
            operation(&instruction.op),
        )?;
    }
    writeln!(
        source,
        "def program : Rivet.Program := program.suffix_{:x}",
        first.address
    )?;
    writeln!(
        source,
        "\n-- At and above each address, `program` fetches as that address's suffix."
    )?;
    for (index, instruction) in instructions.iter().enumerate() {
        let address = instruction.address;
        let proof = match index
            .checked_sub(1)
            .map(|previous| instructions[previous].address)
        {
            None => "fun _ _ => rfl".to_string(),
            Some(previous) => format!(
                "Rivet.Internal.Program.FetchesFrom.skip program.from_{previous:x} (by decide)"
            ),
        };
        writeln!(
            source,
            "theorem program.from_{address:x} : Rivet.Internal.Program.FetchesFrom program program.suffix_{address:x} {address:#x}#64 := {proof}"
        )?;
    }
    Ok(())
}

fn name(value: impl std::fmt::Debug) -> String {
    format!(".{value:?}").to_ascii_lowercase()
}

fn address(value: &Address) -> String {
    let optional = |register| match register {
        Some(register) => format!("some {}", name(register)),
        None => "none".into(),
    };
    format!(
        "{{ base := {}, index := {}, scale := {}, displacement := ({}) }}",
        optional(value.base),
        optional(value.index),
        name(value.scale),
        value.displacement
    )
}

fn operand(value: &Operand) -> String {
    match value {
        Operand::Reg8 { register } => format!("(.reg8 {})", name(register)),
        Operand::Reg16 { register } => format!("(.reg16 {})", name(register)),
        Operand::Reg32 { register } => format!("(.reg32 {})", name(register)),
        Operand::Reg64 { register } => format!("(.reg64 {})", name(register)),
        Operand::Memory {
            width,
            address: value,
        } => format!("(.memory {} {})", name(width), address(value)),
        Operand::Immediate { value } => format!("(.immediate ({value}))"),
    }
}

fn condition(value: rivet_import::program::Condition) -> &'static str {
    use rivet_import::program::Condition::*;
    match value {
        Equal => ".equal",
        NotEqual => ".notEqual",
        Below => ".below",
        AboveOrEqual => ".aboveOrEqual",
        BelowOrEqual => ".belowOrEqual",
        Above => ".above",
        Sign => ".sign",
        Less => ".less",
        GreaterOrEqual => ".greaterOrEqual",
        LessOrEqual => ".lessOrEqual",
        Greater => ".greater",
    }
}

fn operation(value: &Operation) -> String {
    use Operation::*;
    match value {
        Nop => ".nop".into(),
        Binary {
            operation,
            destination,
            source,
        } => format!(
            ".binary {} {} {}",
            name(operation),
            operand(destination),
            operand(source)
        ),
        Mov {
            destination,
            source,
        } => format!(".mov {} {}", operand(destination), operand(source)),
        Lea {
            destination,
            source,
        } => format!(".lea {} {}", operand(destination), address(source)),
        Movzx {
            destination,
            source,
        } => format!(".movzx {} {}", name(destination), operand(source)),
        Movsxd {
            destination,
            source,
        } => format!(".movsxd {} {}", name(destination), operand(source)),
        Jmp { target } => format!(".jmp {target:#x}#64"),
        Jcc {
            condition: value,
            target,
        } => format!(".jcc {} {target:#x}#64", condition(*value)),
        Setcc {
            condition: value,
            destination,
        } => format!(".setcc {} {}", condition(*value), operand(destination)),
        Cmovcc {
            condition: value,
            destination,
            source,
        } => format!(
            ".cmovcc {} {} {}",
            condition(*value),
            operand(destination),
            operand(source)
        ),
        Inc { destination } => format!(".inc {}", operand(destination)),
        Dec { destination } => format!(".dec {}", operand(destination)),
        Ret => ".ret".into(),
        Call { target } => format!(".call {target:#x}#64"),
        Not { destination } => format!(".not {}", operand(destination)),
        Imul {
            destination,
            source,
            immediate,
        } => format!(
            ".imul {} {} {}",
            operand(destination),
            operand(source),
            immediate.map_or("none".into(), |value| format!("(some ({value}))"))
        ),
        Mul { source } => format!(".mul {}", name(source)),
        Tzcnt {
            destination,
            source,
        } => format!(".tzcnt {} {}", operand(destination), operand(source)),
        Shift {
            operation,
            destination,
            count,
        } => format!(
            ".shift {} {} {count}",
            name(operation),
            operand(destination)
        ),
        LoadXmm {
            operation,
            destination,
            source,
        } => format!(
            ".loadXmm {} {} {}",
            name(operation),
            name(destination),
            address(source)
        ),
        StoreXmm {
            operation,
            destination,
            source,
        } => format!(
            ".storeXmm {} {} {}",
            name(operation),
            address(destination),
            name(source)
        ),
        Movd {
            destination,
            source,
        } => format!(".movd {} {}", name(destination), name(source)),
        Pshufd {
            destination,
            source,
            order,
        } => format!(".pshufd {} {} {order}", name(destination), name(source)),
        Push { source } => format!(".push {}", name(source)),
        Pop { destination } => format!(".pop {}", name(destination)),
    }
}
